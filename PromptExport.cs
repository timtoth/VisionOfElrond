using System;
using System.Collections.Generic;
using System.IO;
using System.Threading;
using BepInEx.Logging;
using HarmonyLib;
using Newtonsoft.Json;

namespace JiMEOverlay
{
    // Exports every localization key the game has loaded, with its text in the current language, to prompts.json.
    // The game merges more strings in as it goes, so the file is rewritten whenever the table grows,
    // and keys from earlier sessions are kept. This is the reference for writing prompt-rules.json.
    public static class PromptExport
    {
        private const float CheckInterval = 5f;

        private static readonly AccessTools.FieldRef<Dictionary<string, string[]>> DictionaryRef =
            AccessTools.StaticFieldRefAccess<Dictionary<string, string[]>>(AccessTools.Field(typeof(Localization), "mDictionary"));
        private static readonly AccessTools.FieldRef<int> LanguageIndexRef =
            AccessTools.StaticFieldRefAccess<int>(AccessTools.Field(typeof(Localization), "mLanguageIndex"));

        private static ManualLogSource _log;
        private static string _path;
        private static int _lastCount = -1;
        private static float _nextCheck;
        private static int _writing;

        public static void Init(ManualLogSource log, string dataDir)
        {
            _log = log;
            _path = Path.Combine(dataDir, "prompts.json");
        }

        // Called from the plugin's Update; cheap unless the table has grown.
        public static void Tick(float now)
        {
            if (now < _nextCheck || Interlocked.CompareExchange(ref _writing, 0, 0) != 0)
            {
                return;
            }
            _nextCheck = now + CheckInterval;

            try
            {
                var dictionary = DictionaryRef();
                if (dictionary == null || !Localization.localizationHasBeenSet || dictionary.Count == _lastCount)
                {
                    return;
                }
                _lastCount = dictionary.Count;

                // Copy on the main thread; the game may merge into the dictionary at any time.
                var languageIndex = Math.Max(LanguageIndexRef(), 0);
                var snapshot = new Dictionary<string, string>(dictionary.Count);
                foreach (var pair in dictionary)
                {
                    var values = pair.Value;
                    if (values == null || values.Length == 0)
                    {
                        continue;
                    }
                    var text = languageIndex < values.Length && !string.IsNullOrEmpty(values[languageIndex]) ? values[languageIndex] : values[0];
                    snapshot[pair.Key] = text;
                }
                var language = Localization.language;

                Interlocked.Exchange(ref _writing, 1);
                ThreadPool.QueueUserWorkItem(_ => Write(snapshot, language));
            }
            catch (Exception e)
            {
                _log.LogWarning($"Prompt export failed: {e}");
            }
        }

        private static void Write(Dictionary<string, string> snapshot, string language)
        {
            try
            {
                var file = ReadExisting();
                var prompts = file != null && file.Language == language ? file.Prompts : new SortedDictionary<string, string>(StringComparer.Ordinal);
                var before = prompts.Count;
                var changed = 0;
                foreach (var pair in snapshot)
                {
                    if (!prompts.TryGetValue(pair.Key, out var old) || old != pair.Value)
                    {
                        prompts[pair.Key] = pair.Value;
                        changed++;
                    }
                }
                if (changed == 0 && File.Exists(_path))
                {
                    return;
                }

                var output = new PromptFile
                {
                    Note = "Generated by JiME Overlay from the game's own text. Do not edit; reference it when writing prompt-rules.json.",
                    Language = language,
                    Count = prompts.Count,
                    Prompts = prompts,
                };
                var temp = _path + ".tmp";
                File.WriteAllText(temp, JsonConvert.SerializeObject(output, Formatting.Indented));
                if (File.Exists(_path))
                {
                    File.Delete(_path);
                }
                File.Move(temp, _path);
                _log.LogInfo($"Exported {prompts.Count} prompts ({prompts.Count - before} new) to {_path}");
            }
            catch (Exception e)
            {
                _log.LogWarning($"Prompt export failed: {e}");
            }
            finally
            {
                Interlocked.Exchange(ref _writing, 0);
            }
        }

        private static PromptFile ReadExisting()
        {
            try
            {
                if (!File.Exists(_path))
                {
                    return null;
                }
                var file = JsonConvert.DeserializeObject<PromptFile>(File.ReadAllText(_path));
                if (file != null && file.Prompts != null)
                {
                    file.Prompts = new SortedDictionary<string, string>(file.Prompts, StringComparer.Ordinal);
                    return file;
                }
            }
            catch (Exception e)
            {
                _log.LogWarning($"Could not read existing {_path}, starting fresh: {e.Message}");
            }
            return null;
        }

        private class PromptFile
        {
            [JsonProperty("_note")] public string Note;
            [JsonProperty("language")] public string Language;
            [JsonProperty("count")] public int Count;
            [JsonProperty("prompts")] public SortedDictionary<string, string> Prompts;
        }
    }
}
